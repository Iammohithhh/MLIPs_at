"""Generate the element table used by the atomic viewer from ASE's data tables.

Covalent radii: Cordero et al., "Covalent radii revisited", Dalton Trans. 2008,
2832-2838, doi:10.1039/B801115J (as tabulated in ase.data.covalent_radii).
Elements without a Cordero value carry ASE's placeholder (2.0 Å); they are
exported as null so the viewer can flag them instead of trusting a fake radius.
Colours: Jmol colour scheme (as tabulated in ase.data.colors.jmol_colors).

Usage: python -m atlas_pipeline.elements ../atlas/src/lib/structure/elements.generated.ts
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import ase
from ase.data import atomic_names, chemical_symbols, covalent_radii
from ase.data import missing as ASE_MISSING
from ase.data.colors import jmol_colors


def element_rows() -> list[dict]:
    rows = []
    for z in range(1, len(chemical_symbols)):
        r = float(covalent_radii[z])
        # Jmol defines colours up to Z = 109; heavier elements get a neutral grey.
        rgb = jmol_colors[z] if z < len(jmol_colors) else (0.6, 0.6, 0.6)
        rows.append(
            {
                "z": z,
                "symbol": chemical_symbols[z],
                "name": atomic_names[z],
                "covalentRadius": None if r == ASE_MISSING else round(r, 3),
                "color": "#{:02x}{:02x}{:02x}".format(*(int(round(c * 255)) for c in rgb)),
            }
        )
    return rows


def render_ts(rows: list[dict]) -> str:
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
    return f"""// GENERATED by pipeline/atlas_pipeline/elements.py from ASE {ase.__version__} — do not edit.
// Covalent radii (Å): Cordero et al., Dalton Trans. 2008, 2832-2838, doi:10.1039/B801115J.
// null = no Cordero value (ASE uses a 2.0 Å placeholder). Colours: Jmol scheme (grey beyond Z = 109).

export interface ElementRow {{
  z: number;
  symbol: string;
  name: string;
  covalentRadius: number | null;
  color: string;
}}

export const ELEMENT_SOURCE = {{
  generator: 'ase {ase.__version__}',
  radii: 'Cordero et al., Dalton Trans. 2008, 2832-2838, doi:10.1039/B801115J',
  colors: 'Jmol colour scheme',
}} as const;

export const ELEMENTS: readonly ElementRow[] = [
{body},
];
"""


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    out = Path(argv[1])
    out.write_text(render_ts(element_rows()), encoding="utf-8")
    print(f"wrote {out} ({len(element_rows())} elements)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
